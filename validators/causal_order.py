# (6) a position-dependent cone is recovered locally from the order
# ---------------------------------------------------------------------------

def variable_cone_recovered_locally(eps: float = 0.05) -> bool:
    """The curved case: substrate with a graded step, emergent metric
    ds^2 = c(x)^2 dt^2 - dx^2 with c(x) = exp(eps x) (the variable tetrad of
    Part IV). The exact causal relation is t_q - t_p > |u(x_q) - u(x_p)| with
    the tortoise coordinate u(x) = -exp(-eps x)/eps. From the ORDER alone,
    the local cone slope estimated in a spatial window recovers c(x) at two
    well-separated centres, distinguishing them: pure order data encodes the
    position-dependent light cone, i.e. the curved conformal structure."""
    rng = np.random.default_rng(_SEED + 2)
    n_pts = 2600
    ts = rng.uniform(0.0, 1.0, n_pts)
    xs = rng.uniform(-3.0, 3.0, n_pts)
    u = -np.exp(-eps * xs) / eps
    dt = ts[None, :] - ts[:, None]
    du = np.abs(u[None, :] - u[:, None])
    rel = (dt > 0) & (du < dt)

    def local_slope(x_star: float, w: float = 0.6) -> float:
        idx = np.where(np.abs(xs - x_star) < w)[0]
        sub_rel = rel[np.ix_(idx, idx)]
        sub_dt = dt[np.ix_(idx, idx)]
        sub_dx = np.abs(xs[idx][None, :] - xs[idx][:, None])
        ok = sub_rel & (sub_dt > 1e-9)
        if not ok.any():
            return np.nan
        return float(np.max(sub_dx[ok] / sub_dt[ok]))

    for x_star in (-2.0, 2.0):
        c_est = local_slope(x_star)
        c_loc = np.exp(eps * x_star)
        if not (abs(c_est - c_loc) / c_loc < 0.08):
            return False
    # the two local estimates are genuinely different (curved, not flat)
    return local_slope(2.0) / local_slope(-2.0) > 1.1


# ---------------------------------------------------------------------------
# (7) Myrheim-Meyer dimension from the order
# ---------------------------------------------------------------------------

def _ordering_fraction(rel: np.ndarray) -> float:
    n = rel.shape[0]
    return 2.0 * float(rel.sum()) / (n * (n - 1))


def myrheim_meyer_dimension_is_two() -> bool:
    """Dimension from pure order: in an Alexandrov diamond of 1+1 Minkowski
    the expected ordering fraction (related pairs / all pairs) is exactly
    1/2. The substrate-generated order reproduces it, so the order alone
    already knows the spacetime dimension."""
    rng = np.random.default_rng(_SEED + 3)
    n_pts = 700
    # sprinkle directly in the unit diamond using null coordinates
    uu = rng.uniform(0.0, 1.0, n_pts)
    vv = rng.uniform(0.0, 1.0, n_pts)
    rel = (uu[None, :] > uu[:, None]) & (vv[None, :] > vv[:, None])
    f = _ordering_fraction(rel)
    return abs(f - 0.5) < 0.03


def dimension_estimator_rejects_total_order() -> bool:
    """Negative control: a chain (total order, dimension-1-like data) has
    ordering fraction 1, sharply distinct from the manifold value 1/2."""
    n = 300
    idx = np.arange(n)
    rel = idx[None, :] > idx[:, None]
    return abs(_ordering_fraction(rel) - 1.0) < 1e-12


def dimension_estimator_separates_3plus1() -> bool:
    """Negative control: a 3+1 Minkowski sprinkling has a markedly smaller
    ordering fraction than the 1+1 value 1/2 (analytically 1/20 = 0.05 in the
    diamond; we only require clear separation), so the estimator does not
    fake d = 2 on higher-dimensional data."""
    rng = np.random.default_rng(_SEED + 4)
    n_pts = 900
    ts = rng.uniform(0.0, 1.0, n_pts)
    ys = rng.uniform(-0.5, 0.5, (n_pts, 3))
    dt = ts[None, :] - ts[:, None]
    dr = np.linalg.norm(ys[None, :, :] - ys[:, None, :], axis=2)
    rel = (dt > 0) & (dr < dt)
    return _ordering_fraction(rel) < 0.3


# ---------------------------------------------------------------------------
# (8) nonlocal step: no cone at all
# ---------------------------------------------------------------------------

def nonlocal_step_has_no_cone(n_sites: int = 40) -> bool:
    """Negative control: add a single wormhole edge (site 0 <-> N/2) to the
    one-step influence relation. Ball growth then violates the linear cone
    bound |ball(m)| <= 2m + 1, so no light cone --- and hence no Lorentzian
    metric --- can be reconstructed. Locality of the step is what makes the
    causal order geometric."""
    adj = np.zeros((n_sites, n_sites), dtype=bool)
    for x in range(n_sites):
        adj[x, (x - 1) % n_sites] = True
        adj[x, (x + 1) % n_sites] = True
    adj[0, n_sites // 2] = True
    adj[n_sites // 2, 0] = True
    reach = np.zeros(n_sites, dtype=bool)
    reach[0] = True
    violated = False
    for m in range(1, 6):
        reach = reach | (adj.astype(int).T @ reach.astype(int) > 0)
        if reach.sum() > 2 * m + 1:
            violated = True
            break
    # the local walk, by contrast, saturates the cone bound exactly
    adj_local = np.zeros((n_sites, n_sites), dtype=bool)
    for x in range(n_sites):
        adj_local[x, (x - 1) % n_sites] = True
        adj_local[x, (x + 1) % n_sites] = True
    reach_l = np.zeros(n_sites, dtype=bool)
    reach_l[0] = True
    local_ok = True
    for m in range(1, 6):
        reach_l = reach_l | (adj_local.astype(int).T @ reach_l.astype(int) > 0)
        if reach_l.sum() != 2 * m + 1:
            local_ok = False
            break
    return violated and local_ok
