# ---------------------------------------------------------------------------
# The substrate: a local coined quantum walk on a line
# ---------------------------------------------------------------------------

def _walk_unitary(n_sites: int, theta: float) -> np.ndarray:
    """Coined walk U = S (C x I): coin rotation by theta, then coin-conditioned
    shift (coin 0 -> left, coin 1 -> right), periodic boundary. Basis ordering:
    index = 2*site + coin."""
    dim = 2 * n_sites
    C = np.array(
        [[np.cos(theta), -np.sin(theta)], [np.sin(theta), np.cos(theta)]]
    )
    U = np.zeros((dim, dim))
    for x in range(n_sites):
        xl = (x - 1) % n_sites
        xr = (x + 1) % n_sites
        for cin in range(2):
            # coin acts first: |x, cin> -> sum_cout C[cout, cin] |x, cout>
            # then shift: cout = 0 moves left, cout = 1 moves right
            U[2 * xl + 0, 2 * x + cin] += C[0, cin]
            U[2 * xr + 1, 2 * x + cin] += C[1, cin]
    return U


def _site_support(psi: np.ndarray, n_sites: int, tol: float = 1e-13) -> np.ndarray:
    """Boolean site support of a walk state."""
    prob = psi.reshape(n_sites, 2)
    return (np.abs(prob) > tol).any(axis=1)


def support_outside_ball_is_exactly_zero(n_steps: int = 7) -> bool:
    """Locality of the substrate step: after n steps from a point seed the
    amplitude on every site with |x - x0| > n is exactly zero (below 1e-13),
    for a generic (Hadamard-angle) coin. This is the strict support cone."""
    n_sites = 4 * n_steps + 5
    x0 = n_sites // 2
    U = _walk_unitary(n_sites, np.pi / 4)
    psi = np.zeros(2 * n_sites)
    psi[2 * x0] = 1.0
    for _ in range(n_steps):
        psi = U @ psi
    supp = _site_support(psi, n_sites)
    sites = np.arange(n_sites)
    outside = np.abs(sites - x0) > n_steps
    return not supp[outside].any()


def support_cone_edge_is_attained(n_steps: int = 7) -> bool:
    """The strict cone is sharp: the edge sites x0 +- n carry nonzero
    amplitude (the ballistic component of the coined walk), so the causal
    cone of the substrate has slope exactly 1 site/step."""
    n_sites = 4 * n_steps + 5
    x0 = n_sites // 2
    U = _walk_unitary(n_sites, np.pi / 4)
    psi = np.zeros(2 * n_sites)
    psi[2 * x0] = 1.0
    for _ in range(n_steps):
        psi = U @ psi
    prob = np.abs(psi.reshape(n_sites, 2)) ** 2
    site_prob = prob.sum(axis=1)
    return site_prob[x0 - n_steps] > 1e-12 and site_prob[x0 + n_steps] > 1e-12


# ---------------------------------------------------------------------------
# (2) the influence relation on events is a causal partial order
# ---------------------------------------------------------------------------

def _event_order_matrix(t_max: int, x_half: int) -> tuple[np.ndarray, list]:
    """Relation matrix on events (t, x), t in [0, t_max], |x| <= x_half:
    p precedes q iff t_q > t_p and |x_q - x_p| <= t_q - t_p (the strict
    support cone certified above)."""
    events = [(t, x) for t in range(t_max + 1) for x in range(-x_half, x_half + 1)]
    n = len(events)
    rel = np.zeros((n, n), dtype=bool)
    for i, (t1, x1) in enumerate(events):
        for j, (t2, x2) in enumerate(events):
            rel[i, j] = (t2 > t1) and abs(x2 - x1) <= (t2 - t1)
    return rel, events


def causal_relation_is_partial_order() -> bool:
    """The substrate influence relation is a strict partial order:
    irreflexive, antisymmetric, and transitive (checked exhaustively via the
    boolean relation matrix on a finite event grid)."""
    rel, _events = _event_order_matrix(t_max=6, x_half=6)
    irreflexive = not rel.diagonal().any()
    antisymmetric = not (rel & rel.T).any()
    # transitivity: rel o rel  subset of  rel
    composed = (rel.astype(int) @ rel.astype(int)) > 0
    transitive = not (composed & ~rel).any()
    return irreflexive and antisymmetric and transitive


# ---------------------------------------------------------------------------
# (3) the emergent IR cone sits inside the strict lattice cone
# ---------------------------------------------------------------------------

def emergent_cone_inside_strict_cone() -> bool:
    """The infrared (metric) cone of the walk is bounded by the strict
    support cone. For the coined walk cos(omega) = cos(k) cos(theta), the
    group velocity satisfies max_k |v_g| = cos(theta) <= 1, with equality
    exactly at the massless point theta = 0. Checked numerically on a fine
    k-grid for several coin angles."""
    ks = np.linspace(1e-6, np.pi - 1e-6, 20001)
    for theta in (0.0, 0.2, np.pi / 4, 1.1):
        cw = np.clip(np.cos(ks) * np.cos(theta), -1.0, 1.0)
        omega = np.arccos(cw)
        vg = np.gradient(omega, ks)
        vmax = np.max(np.abs(vg))
        if vmax > 1.0 + 1e-6:
            return False
        if abs(vmax - np.cos(theta)) > 5e-3:
            return False
    # equality only at the massless point
    return abs(np.cos(0.0) - 1.0) < 1e-15 and np.cos(0.2) < 1.0


