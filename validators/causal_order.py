def _sprinkle_flat(n_pts: int, c: float, t_len: float, x_len: float, seed: int):
    rng = np.random.default_rng(seed)
    ts = rng.uniform(0.0, t_len, n_pts)
    xs = rng.uniform(-x_len / 2, x_len / 2, n_pts)
    return ts, xs


def _flat_relation(ts, xs, c):
    dt = ts[None, :] - ts[:, None]
    dx = xs[None, :] - xs[:, None]
    return (dt > 0) & (np.abs(dx) < c * dt)


def order_recovers_light_cone_slope(c_true: float = 0.7) -> bool:
    """Malament/HKM, executable half: on a sprinkled event set whose ONLY
    retained structure is the order relation, the light-cone slope c (the
    conformal class of the 1+1 metric) is re-extracted by bracketing:

        sup over related pairs of |dx|/dt  <  c  <  inf over unrelated
        (future-pointing) pairs of |dx|/dt,

    and the bracket is tight around the true emergent speed."""
    ts, xs = _sprinkle_flat(900, c_true, 1.0, 1.4, _SEED)
    rel = _flat_relation(ts, xs, c_true)
    dt = ts[None, :] - ts[:, None]
    dx = np.abs(xs[None, :] - xs[:, None])
    future = dt > 1e-9
    ratio = np.where(future, dx / np.where(future, dt, 1.0), np.nan)
    sup_related = np.nanmax(np.where(rel, ratio, np.nan))
    inf_unrelated = np.nanmin(np.where(future & ~rel, ratio, np.nan))
    bracket_ok = sup_related < c_true < inf_unrelated
    tight = (inf_unrelated - sup_related) / c_true < 0.05
    return bool(bracket_ok and tight)


def counting_recovers_proper_time(c_true: float = 0.7) -> bool:
    """Causal-set completion: the number of sprinkled events inside the
    Alexandrov interval I(p, q) estimates its volume, and with the cone
    slope already recovered from the order, the proper time between p and q
    is recovered:  tau_est = sqrt(2 N_I / (rho c)).  Order + counting = the
    full metric, not just its conformal class."""
    t_len, x_len, n_pts = 1.0, 1.4, 4000
    rho = n_pts / (t_len * x_len)
    ts, xs = _sprinkle_flat(n_pts, c_true, t_len, x_len, _SEED + 1)
    p = (0.05, 0.0)
    q = (0.95, 0.1)
    tau_true = np.sqrt((q[0] - p[0]) ** 2 - (q[1] - p[1]) ** 2 / c_true**2)
    in_future_p = (ts > p[0]) & (np.abs(xs - p[1]) < c_true * (ts - p[0]))
    in_past_q = (ts < q[0]) & (np.abs(xs - q[1]) < c_true * (q[0] - ts))
    n_interval = int(np.sum(in_future_p & in_past_q))
    # coordinate area of the interval is c tau^2 / 2 (boost invariant)
    tau_est = np.sqrt(2.0 * n_interval / (rho * c_true))
    rel_err = abs(tau_est - tau_true) / tau_true
    # Poisson fluctuation of the count translates to ~ 1/(2 sqrt(N_I)) on tau
    tol = 4.0 / (2.0 * np.sqrt(max(n_interval, 1)))
    return n_interval > 200 and rel_err < max(tol, 0.05)


