"""Build refs_letter.bib as the exact subset of refs_master.bib the letter cites.

Copying entries rather than retyping them: the master bibliography was audited
in July and carries DOIs, so re-entering the metadata by hand would be a place
for silent drift.
"""
import io, os, re

MASTER = r"C:\Users\Nelson\Dev\physics\Protoespacio_Dirac_Weyl_2026\current_submission\master_programme_2026-06-10\refs_master.bib"
LETTER_DIR = r"C:\Users\Nelson\Dev\physics\Protoespacio_Dirac_Weyl_2026\current_submission\letter_sign_and_scale_2026-09-16"
TEX = os.path.join(LETTER_DIR, "letter_sign_and_scale.tex")
OUT = os.path.join(LETTER_DIR, "refs_letter.bib")

tex = io.open(TEX, encoding="utf8").read()
keys = set()
for m in re.finditer(r"\\cite\{([^}]*)\}", tex):
    for k in m.group(1).split(","):
        k = k.strip()
        if k:
            keys.add(k)

src = io.open(MASTER, encoding="utf8").read()
# split into entries on '@' at the start of a line
entries = {}
for m in re.finditer(r"(?m)^@(\w+)\s*\{\s*([^,\s]+)\s*,", src):
    start = m.start()
    nxt = re.search(r"(?m)^@", src[m.end():])
    end = m.end() + (nxt.start() if nxt else len(src) - m.end())
    entries[m.group(2)] = src[start:end].rstrip() + "\n"

found = sorted(k for k in keys if k in entries)
missing = sorted(k for k in keys if k not in entries)

with io.open(OUT, "w", encoding="utf8") as f:
    f.write("% Subset of refs_master.bib cited by letter_sign_and_scale.tex,\n"
            "% plus the two entries specific to the letter (companion, repository).\n"
            "% Generated by scratchpad/make_letter_bib.py -- do not hand-edit the\n"
            "% copied entries; change refs_master.bib and regenerate.\n\n")
    for k in found:
        f.write(entries[k])
        f.write("\n")

print("cited keys: %d" % len(keys))
print("copied from master: %d" % len(found))
print("NOT in master (must be added by hand): %s" % (missing or "none"))
